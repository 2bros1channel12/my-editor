"""Replaceable seams for future media, project, job, model and rendering implementations."""

from pathlib import Path
from typing import Protocol, Any
from .model_runtime import LocalProvider as InferenceProvider


class MediaProcessor(Protocol):
    def probe(self, path: Path) -> dict[str, Any]: ...


class ProjectRepository(Protocol):
    def open(self, path: Path) -> dict[str, Any]: ...
    def save(self, project: dict[str, Any]) -> None: ...


class ProjectPersistence(Protocol):
    """Nondestructive local project storage; original media is always read-only."""

    def create(self, root: Path, name: str, settings: dict[str, Any] | None = None) -> dict[str, Any]: ...
    def open(self, root: Path) -> dict[str, Any]: ...
    def add_asset(self, project_id: str, source_path: Path, metadata: dict[str, Any]) -> str: ...
    def save_state(self, project_id: str, state: dict[str, Any], *, checkpoint: bool = False) -> None: ...


class JobQueue(Protocol):
    def submit(self, operation: str, payload: dict[str, Any]) -> str: ...
    def status(self, job_id: str) -> dict[str, Any]: ...


class Renderer(Protocol):
    def health(self) -> dict[str, Any]: ...
